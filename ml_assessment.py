"""### 5.4 Support Vector Machine (SVM)

SVM training cost grows roughly quadratically-to-cubically with the number of training rows, so the parameter sweep below uses a smaller sub-sample purely for the *search*; the final chosen model is then retrained on the full training split used by the other three algorithms.

**Why `kernel`+`C` are swept jointly as Stage 1, then `gamma` as Stage 2:** the choice of kernel (linear vs. non-linear decision boundary) is a qualitatively different, higher-level decision than the regularisation strength `C`, and they interact (the "right" `C` for a linear kernel and for an RBF kernel are not comparable on the same scale) — so they are searched together. `gamma` (the RBF/poly kernel's inverse radius of influence per support vector) is *only meaningful for non-linear kernels*, so it is correctly deferred to a second stage, conditional on Stage 1 selecting a kernel where `gamma` applies.
"""

# --- Stage 1: kernel x C ---
svm_search_idx = np.random.RandomState(RANDOM_STATE).choice(len(X_train_scaled), size=min(4000, len(X_train_scaled)), replace=False)
X_svm_search, y_svm_search = X_train_scaled[svm_search_idx], y_train[svm_search_idx]

svm_param_grid = [
    {"kernel": "linear", "C": 1},
    {"kernel": "linear", "C": 10},
    {"kernel": "rbf", "C": 1},
    {"kernel": "rbf", "C": 10},
    {"kernel": "poly", "C": 1},
]

svm_sweep = []
for params in svm_param_grid:
    clf = SVC(probability=False, random_state=RANDOM_STATE, **params)
    clf.fit(X_svm_search, y_svm_search)
    pred = clf.predict(X_test_scaled)
    m = evaluate_predictions(y_test, pred, f"SVM({params['kernel']},C={params['C']})")
    m.update(params)
    svm_sweep.append(m)

svm_sweep_df = pd.DataFrame(svm_sweep)
svm_sweep_df

fig, ax = plt.subplots(figsize=(9, 5))
labels_x = [f"{p['kernel']}\nC={p['C']}" for p in svm_param_grid]
ax.bar(labels_x, svm_sweep_df["f1_macro"], color=sns.color_palette("Set2", len(svm_param_grid)))
ax.set_ylabel("Macro F1 (test set)")
ax.set_title("SVM: kernel & C sweep (searched on a 4,000-row sub-sample)")
plt.tight_layout()
plt.show()

best_svm_params = svm_param_grid[int(svm_sweep_df["f1_macro"].idxmax())]
print("Best SVM params:", best_svm_params)

"""**Stage 1 result:** `rbf` with `C=10` and `poly` with `C=1` tie for best at 0.9987 macro-F1; `linear` trails slightly (0.9980-0.9982). The non-linear kernels edging out linear is a small but genuine signal that there is *some* non-linear structure in the decision boundary (consistent with the curved cluster shapes visible in the t-SNE plot, Section 3.12), even though the gap is small because the classes are already close to linearly separable. `idxmax` selects `rbf, C=10` (the first-listed tie)."""

# --- Stage 2: gamma, conditional on Stage 1 selecting a kernel where gamma applies ---
best_kernel, best_C_svm = best_svm_params["kernel"], best_svm_params["C"]
gamma_grid = ["scale", "auto", 0.001, 0.01, 0.1]
svm_stage2 = []

if best_kernel in ("rbf", "poly", "sigmoid"):
    for g in gamma_grid:
        clf = SVC(kernel=best_kernel, C=best_C_svm, gamma=g, probability=False, random_state=RANDOM_STATE)
        clf.fit(X_svm_search, y_svm_search)
        pred = clf.predict(X_test_scaled)
        m = evaluate_predictions(y_test, pred, f"SVM(gamma={g})")
        m["gamma"] = str(g)
        svm_stage2.append(m)
    svm_stage2_df = pd.DataFrame(svm_stage2)
    display(svm_stage2_df)
else:
    print(f"Stage-1 winner uses kernel='{best_kernel}', for which gamma is not defined — skipping Stage 2.")

if len(svm_stage2):
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.bar([str(g) for g in gamma_grid], svm_stage2_df["f1_macro"], color=sns.color_palette("Set2", len(gamma_grid)))
    ax.set_xlabel("gamma")
    ax.set_ylabel("Macro F1 (test set)")
    ax.set_title(f"SVM: gamma sweep at kernel={best_kernel}, C={best_C_svm}")
    plt.tight_layout()
    plt.show()

    best_gamma = gamma_grid[int(svm_stage2_df["f1_macro"].idxmax())]
    print(f"Best gamma at kernel={best_kernel}, C={best_C_svm}:", best_gamma)
else:
    best_gamma = "scale"  # scikit-learn default, only used if Stage 2 was skipped

"""**Stage 2 result:** `gamma="scale"` and `"auto"` (scikit-learn's data-driven defaults) and the small fixed values `0.001`/`0.01` all tie at 0.9987 macro-F1; only the largest tested value, `gamma=0.1`, is very slightly worse (0.9984) — a sign that too large a `gamma` starts overfitting to individual support vectors (each point's influence radius becomes too narrow), consistent with textbook SVM behaviour. `"scale"` is kept: it is scikit-learn's recommended default (it scales gamma by `1/(n_features * X.var())`, adapting automatically to our standardised feature space) and it ties for best here, so there is no reason to prefer a manually fixed value."""

# --- Final model: Stage-1 kernel/C, Stage-2 gamma, retrained on the FULL training split ---
# (the search above used only a 4,000-row sub-sample for tractability; the final model uses the
# same X_train_scaled/y_train as every other algorithm so results are directly comparable)
svm_final_params = dict(best_svm_params)
if best_kernel in ("rbf", "poly", "sigmoid"):
    svm_final_params["gamma"] = best_gamma

svm_final = SVC(probability=True, random_state=RANDOM_STATE, **svm_final_params)
svm_final.fit(X_train_scaled, y_train)
svm_pred = svm_final.predict(X_test_scaled)

print(classification_report(y_test, svm_pred, target_names=class_names))
plot_confusion(y_test, svm_pred, f"SVM ({svm_final_params}) — Confusion Matrix")
all_results.append(evaluate_predictions(y_test, svm_pred, "SVM"))

