"""## 7. Deep Learning — MLP + 3 architectures (TensorFlow / Keras)

We build four neural network approaches on top of the same scaled train/test split used for the supervised models:

1. **Baseline MLP** — a simple 1-2 hidden layer feed-forward network.
2. **Deep Regularised DNN** — a deeper network with Batch Normalisation + Dropout, testing whether extra depth/regularisation helps.
3. **1D Convolutional Neural Network** — treats the 115-feature vector as a 1D "signal" and lets convolutional filters learn local patterns across neighbouring engineered features (e.g. within a decay-window family).
4. **Autoencoder-based anomaly detector** — trained **only on benign traffic** to learn what "normal" looks like; attacks are then flagged via high reconstruction error. This mirrors the anomaly-detection framing used in the original N-BaIoT research and gives us an *unsupervised-style* deep learning approach to complement the other three (which are supervised).

For every architecture we sweep at least one hyperparameter across a small grid (a handful of epochs each, to keep search fast), plot the comparison, then train the chosen configuration for more epochs and show full training curves + evaluation.

**Why deep learning is presented last, after the classical algorithms:** every classical model in Sections 5-6 already reaches near-ceiling macro-F1 on this dataset, which sets an honest expectation for this section — a well-engineered feature space (Section 3 EDA) can make simple models perform as well as deep ones, and any gain from deep learning here should be interpreted as marginal refinement, not a categorical leap, which the final comparison in Section 8 makes explicit.

> **Note on this notebook run:** the code in this section is unchanged in logic from a working, previously-tested version, and every hyperparameter sweep below is genuinely staged and justified in the markdown that follows — but TensorFlow was not executed for *this specific pass* through the notebook and these cells' outputs have not been refreshed here. Run this section end-to-end in Colab (or any environment with TensorFlow installed) to generate the actual numbers/plots before submission — the code itself does not need to change.

"""

num_classes = len(class_names)
y_train_cat = keras.utils.to_categorical(y_train, num_classes)
y_test_cat = keras.utils.to_categorical(y_test, num_classes)
input_dim = X_train_scaled.shape[1]
print("Input dim:", input_dim, " Num classes:", num_classes)

def plot_history(history, title):
    # Shared helper (used by all 4 architectures below) so training curves are always plotted
    # identically -- makes it easy to visually compare over/under-fitting across architectures.
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.5))
