cv_df = pd.DataFrame(cv_rows)
print("\n5-fold cross-validated macro-F1:")
print(cv_df.to_string(index=False))

fig, ax = plt.subplots(figsize=(9, 5))
ax.bar(cv_df["model"], cv_df["cv_mean"], yerr=cv_df["cv_std"], capsize=6,
       color=["#4c72b0", "#dd8452", "#55a868", "#c44e52"])
ax.set_ylim(0.99, 1.001)   # zoomed: full 0-1 axis would render all four bars identical
ax.set_ylabel("Cross-validated macro-F1")
