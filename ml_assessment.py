"""## 6. Unsupervised Learning — 3 algorithms

Here we deliberately **hide the labels** and ask each algorithm to discover structure on its own. We still have the true labels available, so after clustering we can score how well the *discovered* groups line up with the *true* traffic classes using Adjusted Rand Index (ARI) and Normalised Mutual Information (NMI) — this tells us whether the natural structure in the data (as seen in the PCA/t-SNE plots) really does correspond to benign vs. gafgyt vs. mirai traffic.

For clustering we scale features the same way as before and, for the two computationally heavier algorithms (Agglomerative Clustering and DBSCAN), use a smaller sub-sample.

**Why each algorithm here also gets a staged, 2-parameter search:** an unsupervised algorithm has no labels to optimise against directly, so its *internal* hyperparameter (number of clusters `k`, `eps`/`min_samples`, linkage) is chosen first using a purely internal, label-free criterion (silhouette score) — exactly as a real deployment would have to, since true labels won't be available in production. The *second*-stage parameter for each algorithm (K-Means: initialisation strategy; Agglomerative: distance metric; DBSCAN: distance metric) is then swept at that fixed configuration, and — because we happen to have ground truth here — we additionally report ARI/NMI at each second-stage setting purely for research insight into when internal (silhouette) and external (ARI/NMI) criteria agree or disagree.
"""

# Shared clustering input: same scaled data used by the supervised models, concatenated back into
# one array. WHY concatenate train+test here (unlike the supervised sections): clustering is
# unsupervised, so there is no "train/test leakage" concern in the supervised sense — using all
# available (scaled) rows gives the clustering algorithms the largest, most representative sample
# of the true data distribution to find structure in.
X_cluster = np.vstack([X_train_scaled, X_test_scaled])
y_cluster_true = np.concatenate([y_train, y_test])
print("Clustering input shape:", X_cluster.shape)

"""### 6.1 K-Means

Model selection for K-Means uses two classic diagnostics:
- **Elbow method**: inertia (within-cluster sum of squares) vs. k — look for the "elbow" where adding clusters stops giving big improvements.
- **Silhouette score**: how well-separated/compact clusters are (higher is better, range -1 to 1).

**Why `k` is Stage 1 and `init`/`n_init` is Stage 2:** `k` fundamentally changes what problem is being solved (how many groups to look for), while `init`/`n_init` only affect how reliably K-Means' local, non-convex optimisation finds a good solution *for a given k* — so the number of clusters must be settled first.

"""

# --- Stage 1: k (number of clusters) ---
k_grid = list(range(2, 9))
inertias, silhouettes_km = [], []

# Silhouette is O(n^2); use a sub-sample purely for scoring to keep this responsive
sil_sample_idx = np.random.RandomState(RANDOM_STATE).choice(len(X_cluster), size=min(5000, len(X_cluster)), replace=False)

for k in k_grid:
    km = KMeans(n_clusters=k, random_state=RANDOM_STATE, n_init=10)
    labels_k = km.fit_predict(X_cluster)
    inertias.append(km.inertia_)
    silhouettes_km.append(silhouette_score(X_cluster[sil_sample_idx], labels_k[sil_sample_idx]))

km_diag_df = pd.DataFrame({"k": k_grid, "inertia": inertias, "silhouette": silhouettes_km})
km_diag_df

fig, axes = plt.subplots(1, 2, figsize=(13, 5))
axes[0].plot(k_grid, inertias, marker="o")
axes[0].set_xlabel("k (number of clusters)")
axes[0].set_ylabel("Inertia (within-cluster SSE)")
axes[0].set_title("K-Means Elbow Method")

axes[1].plot(k_grid, silhouettes_km, marker="o", color="darkorange")
axes[1].set_xlabel("k (number of clusters)")
axes[1].set_ylabel("Silhouette score")
axes[1].set_title("K-Means Silhouette Analysis")
plt.tight_layout()
plt.show()

# WHY select k by silhouette rather than "eyeballing" the elbow: the elbow is often ambiguous to
# read precisely (as it is here — inertia decreases smoothly with no single sharp bend), whereas
# silhouette gives an unambiguous, quantitative internal criterion we can select on programmatically.
best_k = k_grid[int(np.argmax(silhouettes_km))]
print("Best k by silhouette score:", best_k, " (true number of classes = 3, for reference)")

"""**Stage 1 result:** silhouette rises fairly steadily from k=2 (0.539) to a peak at **k=6** (0.674), then dips slightly at k=7 before recovering at k=8 — the elbow plot alone would not have made this obvious, confirming the choice to select programmatically by silhouette rather than by eye. Notably, k=6 (chosen) is double the true number of classes (3) — the geometric best split of the feature space subdivides at least one true class into multiple tighter sub-clusters (plausibly Mirai and Gafgyt each splitting into sub-behaviours), which Stage 2 investigates further."""

# --- Stage 2: init strategy & n_init, at the Stage-1 best k ---
# WHY: K-Means' objective is non-convex, so different random initialisations can converge to
# different local optima. init="k-means++" (smarter, spread-out initial centroids) vs. "random"
# tests whether initialisation quality matters here; n_init (how many independent random restarts
# to run, keeping the best) tests whether a single run is already reliable or whether restarts are
# needed to escape a bad local optimum.
init_grid = ["k-means++", "random"]
n_init_grid = [1, 5, 10, 20]
km_stage2 = []
for init in init_grid:
    for n_init in n_init_grid:
        km = KMeans(n_clusters=best_k, init=init, n_init=n_init, random_state=RANDOM_STATE)
        labels = km.fit_predict(X_cluster)
        sil = silhouette_score(X_cluster[sil_sample_idx], labels[sil_sample_idx])
        ari = adjusted_rand_score(y_cluster_true, labels)
        nmi = normalized_mutual_info_score(y_cluster_true, labels)
        km_stage2.append({"init": init, "n_init": n_init, "silhouette": sil, "ARI": ari, "NMI": nmi, "inertia": km.inertia_})

km_stage2_df = pd.DataFrame(km_stage2)
km_stage2_df

fig, axes = plt.subplots(1, 2, figsize=(13, 5))
for init in init_grid:
    sub = km_stage2_df[km_stage2_df["init"] == init]
    axes[0].plot(sub["n_init"], sub["silhouette"], marker="o", label=init)
    axes[1].plot(sub["n_init"], sub["ARI"], marker="s", label=init)
axes[0].set_xlabel("n_init"); axes[0].set_ylabel("Silhouette"); axes[0].set_title(f"K-Means: silhouette by init strategy (k={best_k})"); axes[0].legend()
axes[1].set_xlabel("n_init"); axes[1].set_ylabel("ARI vs. true labels"); axes[1].set_title(f"K-Means: ARI by init strategy (k={best_k})"); axes[1].legend()
plt.tight_layout()
plt.show()

best_km_row = km_stage2_df.loc[km_stage2_df["silhouette"].idxmax()]
best_init, best_n_init = best_km_row["init"], int(best_km_row["n_init"])
print("Best (init, n_init) by silhouette:", best_init, best_n_init)

"""**Stage 2 result — an important, genuinely counter-intuitive finding:** selecting purely by the internal silhouette criterion picks `init="k-means++", n_init=5` (silhouette 0.674), which is also the configuration used in Stage 1. However, looking at the ARI/NMI columns (only possible because we happen to have ground truth here) tells a different story: that same "best-by-silhouette" configuration only achieves **ARI 0.429 / NMI 0.612**, whereas `init="k-means++", n_init=1` — a *single*, non-restarted run — achieves a noticeably higher **ARI 0.798 / NMI 0.846** despite a *lower* silhouette (0.617). The likely explanation, consistent with Stage 1's finding that k=6 splits the geometric space more finely than the 3 true classes: repeated restarts (n_init≥5) consistently converge to the geometrically tightest 6-way split (which is what silhouette rewards), while a single restart happens to land on a 6-way split that more closely respects the original 3-class boundaries (each true class splitting into two, in a way that stays "pure" per true class) rather than the globally tightest split. This is exactly the kind of unexpected trend the coursework brief asks us to interpret, not just report: **an internal validity metric (silhouette) and an external validity metric (agreement with ground truth) can point to different "best" configurations**, and a practitioner without ground truth (the realistic deployment scenario) would have no way to know this from silhouette alone. We proceed with the silhouette-selected configuration for methodological consistency with Stage 1 (since a production system would only have silhouette available), but flag this tension explicitly, which Section 9.2 then quantifies and Section 12 revisits."""

# --- Final model: Stage-1 best k, Stage-2 best init/n_init (selected by silhouette, see discussion above) ---
kmeans_final = KMeans(n_clusters=best_k, init=best_init, n_init=best_n_init, random_state=RANDOM_STATE)
km_labels = kmeans_final.fit_predict(X_cluster)

ari_km = adjusted_rand_score(y_cluster_true, km_labels)
nmi_km = normalized_mutual_info_score(y_cluster_true, km_labels)
print(f"K-Means (k={best_k}, init={best_init}, n_init={best_n_init}) vs. true labels -> ARI: {ari_km:.3f}, NMI: {nmi_km:.3f}")

# Visualise clusters vs. true labels side-by-side in PCA space
pca_vis = PCA(n_components=2, random_state=RANDOM_STATE).fit(X_cluster)
