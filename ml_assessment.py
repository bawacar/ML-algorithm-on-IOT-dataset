fig, axes = plt.subplots(1, 2, figsize=(14, 6))
sc0 = axes[0].scatter(coords_vis[:, 0], coords_vis[:, 1], c=km_labels, cmap="tab10", s=4, alpha=0.5)
axes[0].set_title(f"K-Means clusters (k={best_k})")
sc1 = axes[1].scatter(coords_vis[:, 0], coords_vis[:, 1], c=y_cluster_true, cmap="tab10", s=4, alpha=0.5)
