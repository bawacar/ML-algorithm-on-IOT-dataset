# --- Final model: cosine metric selected above (deliberately overriding the pure-silhouette ranking; see discussion) ---
final_agg_metric = "cosine"
agg_final = AgglomerativeClustering(n_clusters=best_n_c, linkage=link_for_metric_test, metric=final_agg_metric)
agg_labels = agg_final.fit_predict(X_hier)

