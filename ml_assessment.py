"""### 7.1 Baseline MLP (feed-forward neural network)

**Why `hidden_units` and `learning_rate` are swept jointly (not staged) as the one sweep here:** for a small feed-forward network, network width and optimiser step size interact directly — a larger network with too-large a learning rate can diverge, while a smaller network may need a larger learning rate to train in few epochs. A joint small grid (4 combinations) is cheap enough here that staging would add complexity without saving meaningful compute.
"""

def build_mlp(hidden_units, lr):
    model = keras.Sequential([
        layers.Input(shape=(input_dim,)),
        layers.Dense(hidden_units, activation="relu"),
        layers.Dense(hidden_units // 2, activation="relu"),
        layers.Dense(num_classes, activation="softmax"),
    ])
    model.compile(optimizer=keras.optimizers.Adam(learning_rate=lr),
                  loss="categorical_crossentropy", metrics=["accuracy"])
    return model

# WHY these 4 (hidden_units, lr) combos specifically: they span a small-network/large-lr corner
# (32, 0.01) through progressively larger networks with smaller, more conservative learning rates
# (128, 0.0005) -- testing whether a bigger network needs a gentler learning rate to train stably
# in the short (8-epoch) search budget used here.
mlp_grid = [(32, 0.01), (64, 0.001), (128, 0.001), (128, 0.0005)]
mlp_sweep = []
for hidden_units, lr in mlp_grid:
    model = build_mlp(hidden_units, lr)
    # WHY only 8 epochs for the SEARCH (not the final model, trained longer below): the sweep only
    # needs to rank configurations relative to each other, not reach full convergence -- a short,
    # identical epoch budget per configuration keeps the comparison fair and the search fast.
    hist = model.fit(X_train_scaled, y_train_cat, validation_split=0.15,
                      epochs=8, batch_size=256, verbose=0)
    val_acc = max(hist.history["val_accuracy"])
    mlp_sweep.append({"hidden_units": hidden_units, "lr": lr, "best_val_accuracy": val_acc})

mlp_sweep_df = pd.DataFrame(mlp_sweep)
mlp_sweep_df

fig, ax = plt.subplots(figsize=(9, 5))
labels_x = [f"h={h}\nlr={lr}" for h, lr in mlp_grid]
ax.bar(labels_x, mlp_sweep_df["best_val_accuracy"], color=sns.color_palette("Set2", len(mlp_grid)))
ax.set_ylabel("Best validation accuracy (8 epochs)")
ax.set_title("Baseline MLP: hidden-units / learning-rate sweep")
plt.tight_layout()
plt.show()

best_mlp_units, best_mlp_lr = mlp_grid[int(mlp_sweep_df["best_val_accuracy"].idxmax())]
print("Best MLP config:", best_mlp_units, best_mlp_lr)

mlp_final = build_mlp(best_mlp_units, best_mlp_lr)
# EarlyStopping (patience=5, restore_best_weights=True) is used for every FINAL model in this
# section (not the short search sweeps above) so each final model trains until validation loss
# stops improving, then reverts to its best epoch -- preventing the final reported metrics from
# reflecting an over-trained, overfit snapshot.
early_stop = keras.callbacks.EarlyStopping(monitor="val_loss", patience=5, restore_best_weights=True)
mlp_history = mlp_final.fit(X_train_scaled, y_train_cat, validation_split=0.15,
                             epochs=40, batch_size=256, callbacks=[early_stop], verbose=0)
