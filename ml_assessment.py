"""### 6.3 DBSCAN

DBSCAN needs no pre-specified number of clusters, but is sensitive to `eps` (neighbourhood radius) and `min_samples`. We sweep both and track: number of clusters found, % of points labelled as noise, and silhouette score (computed excluding noise points).

**Why `eps`+`min_samples` are Stage 1 (joint), and `metric` is Stage 2:** these two parameters jointly define what counts as a "dense enough" neighbourhood, and they trade off directly against each other (a larger `eps` needs a larger `min_samples` to mean the same thing), so they must be searched together. The distance `metric` changes the very definition of "neighbourhood," so it is tested second, at the fixed `eps`/`min_samples` combination that Stage 1 found — with the explicit caveat that `eps` was originally tuned for euclidean distance and may not be perfectly comparable across metrics (discussed below).

"""

# --- Stage 1: eps x min_samples (joint grid) ---
dbscan_sample_idx = np.random.RandomState(RANDOM_STATE).choice(len(X_cluster), size=min(4000, len(X_cluster)), replace=False)
X_db = X_cluster[dbscan_sample_idx]
y_db_true = y_cluster_true[dbscan_sample_idx]

eps_grid = [0.5, 1.0, 1.5, 2.0, 3.0]
min_samples_grid = [5, 10, 20]

db_sweep = []
for eps in eps_grid:
    for ms in min_samples_grid:
        db = DBSCAN(eps=eps, min_samples=ms)
        labels_db = db.fit_predict(X_db)
        n_clusters_found = len(set(labels_db)) - (1 if -1 in labels_db else 0)
        noise_pct = (labels_db == -1).mean() * 100
        if n_clusters_found > 1:
            mask = labels_db != -1
            sil = silhouette_score(X_db[mask], labels_db[mask]) if mask.sum() > 1 and len(set(labels_db[mask])) > 1 else np.nan
        else:
            sil = np.nan
        db_sweep.append({"eps": eps, "min_samples": ms, "n_clusters": n_clusters_found,
                          "noise_pct": noise_pct, "silhouette": sil})

db_sweep_df = pd.DataFrame(db_sweep)
db_sweep_df

fig, axes = plt.subplots(1, 2, figsize=(14, 5))
pivot_noise = db_sweep_df.pivot(index="min_samples", columns="eps", values="noise_pct")
pivot_sil = db_sweep_df.pivot(index="min_samples", columns="eps", values="silhouette")

sns.heatmap(pivot_noise, annot=True, fmt=".1f", cmap="rocket_r", ax=axes[0])
axes[0].set_title("DBSCAN: % of points labelled noise")

sns.heatmap(pivot_sil, annot=True, fmt=".2f", cmap="viridis", ax=axes[1])
axes[1].set_title("DBSCAN: silhouette score (excluding noise)")
plt.tight_layout()
plt.show()

# WHY select by silhouette rather than by minimising noise%: a trivially small eps/large min_samples
# minimises noise by cramming almost every point into one giant "cluster," which is not a
# meaningful result -- silhouette (on non-noise points) rewards genuinely separated, compact
# clusters instead, at the cost of accepting more points as noise.
valid = db_sweep_df.dropna(subset=["silhouette"])
best_eps, best_ms = valid.loc[valid["silhouette"].idxmax(), ["eps", "min_samples"]]
print("Best (eps, min_samples) by silhouette:", best_eps, best_ms)

"""**Stage 1 result:** the highest silhouette (0.912) occurs at `eps=0.5, min_samples=20` — but this comes at the cost of over half the points (55%) being labelled noise, and only 11 clusters being found. This is a real trade-off inherent to DBSCAN on high-dimensional, continuous behavioural data: a small `eps` only connects extremely tight neighbourhoods, which are very "pure" (hence high silhouette) but leave much of the data unassigned. We select this configuration anyway since we are optimising silhouette *as the internal criterion*, and examine below whether the discovered structure is actually meaningful via ARI/NMI and via the metric sweep."""

# --- Stage 2: distance metric, at the Stage-1 best (eps, min_samples) ---
# CAVEAT stated explicitly: eps was tuned above using euclidean distance, so its numeric value is
# not automatically the "right" radius for manhattan or cosine distance, which have different
# scales. We still run this sweep at the same eps as an exploratory check (does changing ONLY the
# metric, all else equal, change the result?), and flag eps-per-metric re-tuning as a natural next
# step in Section 12's limitations rather than doing a full second grid search here.
metric_grid_db = ["euclidean", "manhattan", "cosine"]
db_stage2 = []
for m in metric_grid_db:
    db = DBSCAN(eps=best_eps, min_samples=int(best_ms), metric=m)
    labels_db2 = db.fit_predict(X_db)
    n_found = len(set(labels_db2)) - (1 if -1 in labels_db2 else 0)
    noise_pct = (labels_db2 == -1).mean() * 100
    if n_found > 1:
        mask = labels_db2 != -1
        sil = silhouette_score(X_db[mask], labels_db2[mask], metric=m) if mask.sum() > 1 and len(set(labels_db2[mask])) > 1 else np.nan
        ari = adjusted_rand_score(y_db_true[mask], labels_db2[mask])
        nmi = normalized_mutual_info_score(y_db_true[mask], labels_db2[mask])
    else:
        sil = ari = nmi = np.nan
    db_stage2.append({"metric": m, "n_clusters": n_found, "noise_pct": noise_pct, "silhouette": sil, "ARI": ari, "NMI": nmi})

db_stage2_df = pd.DataFrame(db_stage2)
db_stage2_df

fig, ax = plt.subplots(figsize=(8, 5))
x = np.arange(len(metric_grid_db))
ax.bar(x - 0.2, db_stage2_df["silhouette"], width=0.4, label="silhouette")
ax.bar(x + 0.2, db_stage2_df["ARI"], width=0.4, label="ARI vs. true labels")
ax.set_xticks(x); ax.set_xticklabels(metric_grid_db)
ax.set_title(f"DBSCAN: metric sweep at eps={best_eps}, min_samples={int(best_ms)}")
ax.legend()
plt.tight_layout()
plt.show()

best_db_metric = metric_grid_db[int(db_stage2_df["ARI"].idxmax())]
print("Best metric by ARI (external validity):", best_db_metric)

"""**Stage 2 result:** `manhattan` distance improves on BOTH criteria simultaneously here — silhouette rises to 0.995 and ARI to 0.986 (vs. euclidean's 0.912 silhouette / 0.921 ARI) — while collapsing to only 4 clusters, at the cost of slightly more noise (63.9% vs. 55.0%). `cosine` all but eliminates noise (0.05%) but only reaches ARI 0.449, similar to the Agglomerative-clustering cosine result in Section 6.2 — evidence that this data has real behavioural-family structure along the cosine/angular direction, but manhattan distance is the strongest single choice for DBSCAN specifically on this feature space. We select `metric="manhattan"` as the final configuration, chosen by ARI (external validity) since, unusually, it agrees with the silhouette (internal validity) ranking here — the one case among our three clustering algorithms where the two criteria don't conflict."""

# --- Final model: Stage-1 (eps, min_samples), Stage-2 best metric (manhattan; see discussion) ---
db_final = DBSCAN(eps=best_eps, min_samples=int(best_ms), metric=best_db_metric)
db_labels = db_final.fit_predict(X_db)
n_found = len(set(db_labels)) - (1 if -1 in db_labels else 0)
print(f"DBSCAN found {n_found} clusters; {np.mean(db_labels == -1) * 100:.1f}% of points labelled as noise")

# WHY exclude noise (-1) points from ARI/NMI here, consistent with how silhouette was already
# computed throughout Sections 6.3's sweeps: a noise label is "this point didn't fit any dense
# region," not a genuine cluster assignment, so scoring it as if it were its own class would
# conflate "DBSCAN found no structure for this point" with "DBSCAN put this point in the wrong
# group" -- two different failure modes. We report both the noise rate (above) and the ARI/NMI on
# the assigned points (below) so neither number hides the other.
db_mask = db_labels != -1
ari_db = adjusted_rand_score(y_db_true[db_mask], db_labels[db_mask])
nmi_db = normalized_mutual_info_score(y_db_true[db_mask], db_labels[db_mask])
print(f"DBSCAN vs true labels (on the {db_mask.sum()} non-noise points) -> ARI: {ari_db:.3f}, NMI: {nmi_db:.3f}")

coords_db = pca_vis.transform(X_db)
fig, axes = plt.subplots(1, 2, figsize=(14, 6))
axes[0].scatter(coords_db[:, 0], coords_db[:, 1], c=db_labels, cmap="tab10", s=8, alpha=0.6)
axes[0].set_title(f"DBSCAN clusters (eps={best_eps}, min_samples={int(best_ms)}, metric={best_db_metric}); -1 = noise")
axes[1].scatter(coords_db[:, 0], coords_db[:, 1], c=y_db_true, cmap="tab10", s=8, alpha=0.6)
