gafgyt_32 = df.loc[df["label"] == "gafgyt_udp", feature_cols]
gafgyt_64 = pd.read_csv(os.path.join(DATA_DIR, "gafgyt_attacks_udp.csv"))
print(f"Gafgyt rows: {len(gafgyt_32):,}")
