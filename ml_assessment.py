"""## 9. Robustness Checks

The scores reported so far come from a single 75/25 split of an 18,000-row sample.
Three questions that split cannot answer on its own are addressed here: whether the
models have memorised their training data, whether the result depends on one
favourable partition, and whether the full 115-feature space is actually needed.

### 9.1 Overfitting and cross-validation

**Question.** A model that has memorised its training set scores far higher on
training data than on held-out data, so the size of that gap is the direct test.
Separately, five-fold cross-validation shows whether the strong result survives
every partition of the data rather than only the one reported.

**Why here.** Both run on the tuned configurations from Section 5, so the numbers
describe the models actually being reported.
"""

# --- Robustness check 1: overfitting and split-dependence ---
# Every headline score so far comes from one 75/25 split, which cannot distinguish a model
# that has learned the structure from one that has memorised 13,500 rows. Two checks close
# that gap. The train-vs-test gap is the direct test for memorisation; k-fold answers the
# separate question of whether the reported split happened to be an easy one.
#
# Both run on the tuned estimators from Section 5 rather than fresh instances, so the numbers
# describe the models actually being reported rather than a re-tuned approximation of them.
#
# The Pipeline below is not cosmetic. cross_val_score re-splits the data internally, so a
# scaler fitted once beforehand would have already seen every test fold and would leak their
# means and variances into training. Wrapping the scaler in the Pipeline forces sklearn to
# refit it inside each fold, which is the same leakage precaution applied to the main split.
from sklearn.model_selection import StratifiedKFold, cross_val_score
from sklearn.pipeline import Pipeline
from sklearn.base import clone

tuned_models = {
    "Logistic Regression": lr_final,
    "Decision Tree":       dt_final,
    "Random Forest":       rf_final,
    "SVM":                 svm_final,
}

# Part 1: train-vs-test gap. Large positive gap (train >> test) indicates overfitting.
# Predict on both splits with the already-fitted model; no refitting, so the numbers
# correspond exactly to the estimator reported in Section 5.
overfit_rows = []
for name, model in tuned_models.items():
    train_f1 = f1_score(y_train, model.predict(X_train_scaled), average="macro")
    test_f1  = f1_score(y_test,  model.predict(X_test_scaled),  average="macro")
