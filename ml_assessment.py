"""### 6.2 Agglomerative (Hierarchical) Clustering

Hierarchical clustering has quadratic memory/time cost, so both the dendrogram and the parameter sweep use a smaller sub-sample.

**Why `linkage`+`n_clusters` are Stage 1 (joint), and `metric` is Stage 2:** the linkage method (ward/complete/average) defines *how* cluster-to-cluster distance is computed during the merging process, and its interaction with the resulting number of natural clusters is direct (e.g. ward tends to produce more evenly-sized clusters than average), so they are searched jointly. The distance `metric` (euclidean/manhattan/cosine) is a further, independent choice about *what "distance" means* in this 115-dimensional space, tested second once a linkage/cluster-count baseline exists.

"""

hier_sample_idx = np.random.RandomState(RANDOM_STATE).choice(len(X_cluster), size=min(1500, len(X_cluster)), replace=False)
X_hier = X_cluster[hier_sample_idx]
y_hier_true = y_cluster_true[hier_sample_idx]

